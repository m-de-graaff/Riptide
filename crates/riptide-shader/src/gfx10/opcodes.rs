//! Every table is sorted by opcode number so that it can be searched by
//! halving. The three-source vector format also encodes the comparison,
//! two-source and one-source vector operations at fixed bases; those are
//! looked up in their own tables (see [`vop3_name`]), so [`VOP3`] holds only
//! the operations that exist in no other format.

/// One opcode of one format: its number and its mnemonic.
#[derive(Debug, Clone, Copy)]
pub(super) struct Op {
    /// The opcode number as the format's opcode field holds it.
    pub code: u16,
    /// The mnemonic, in the spelling LLVM and Mesa use for this generation.
    pub name: &'static str,
}

/// Builds a table entry.
const fn op(code: u16, name: &'static str) -> Op {
    Op { code, name }
}

/// Finds the mnemonic of an opcode number in a table.
pub(super) fn find(table: &[Op], code: u16) -> Option<&'static str> {
    table
        .binary_search_by_key(&code, |entry| entry.code)
        .ok()
        .map(|at| table[at].name)
}

/// The first three-source opcode number that encodes a two-source operation.
pub(super) const VOP3_VOP2_BASE: u16 = 0x100;
/// The first three-source opcode number that is a three-source operation proper.
pub(super) const VOP3_OWN_BASE: u16 = 0x140;
/// The first three-source opcode number that encodes a one-source operation.
pub(super) const VOP3_VOP1_BASE: u16 = 0x180;
/// One past the last three-source opcode number that encodes a one-source operation.
pub(super) const VOP3_VOP1_END: u16 = 0x200;

/// Finds the mnemonic of an opcode of the three-source vector format, which
/// holds comparisons from 0, two-source operations from 0x100, one-source
/// operations from 0x180, and its own operations everywhere else.
pub(super) fn vop3_name(code: u16) -> Option<&'static str> {
    match code {
        0..VOP3_VOP2_BASE => find(VOPC, code),
        VOP3_VOP2_BASE..VOP3_OWN_BASE => find(VOP2, code - VOP3_VOP2_BASE),
        VOP3_VOP1_BASE..VOP3_VOP1_END => find(VOP1, code - VOP3_VOP1_BASE),
        _ => find(VOP3, code),
    }
}

